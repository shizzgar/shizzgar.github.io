import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';

const source = await readFile('./webgl-recovery.js', 'utf8');
const context = vm.createContext({DOMException, setTimeout, clearTimeout});
const module = new vm.SourceTextModule(source, {context});
await module.link(() => {});
await module.evaluate();
const probe = module.namespace.probeWebGLRecovery;
let releases = 0, count = 0;
const live = {isContextLost:()=>false, getExtension:()=>({loseContext:()=>{releases++;}})};
const lost = {isContextLost:()=>true, getExtension:()=>({loseContext:()=>{releases++;}})};
const doc = fn => ({createElement:()=>({getContext:name=>{count++; return fn(name, count);}})});
assert.equal((await probe({doc:doc(()=>live), waitMs:0})).state, 'available');
assert.equal(releases, 1, 'successful test context is explicitly released');
count=0;releases=0;
assert.equal((await probe({doc:doc(name=>name==='webgl2'?lost:live), waitMs:0})).state, 'available');
assert.equal(count, 2, 'a fresh canvas is used for the fallback type');
assert.equal(releases, 2, 'lost and successful contexts both receive cleanup');
count=0;
assert.equal((await probe({doc:doc(()=>null), waitMs:0})).state, 'unavailable');
assert.equal(count, 6, 'all context types are retried once after a bounded delay');
count=0;
assert.equal((await probe({doc:doc((name,n)=>n>3?live:null), waitMs:0})).state, 'available', 'temporary loss can recover');
count=0;
assert.equal((await probe({doc:doc(()=>{throw new Error('blocked')}), waitMs:0})).state, 'unknown');
assert.equal((await probe({doc:{}, waitMs:0})).state, 'unknown');
const controller = new AbortController();
const pending = probe({doc:doc(()=>null), signal:controller.signal, waitMs:1000});
controller.abort();
await assert.rejects(pending, {name:'AbortError'});
console.log('PASS bounded WebGL recovery probe, independent canvas cleanup, unknowns and cancellation');
